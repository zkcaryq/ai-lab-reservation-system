def build(title, chapters):
    doc = new_doc()
    footer_note(doc, f"{ORG_NAME}｜{title}｜{DOC_VERSION}｜{DOC_DATE}")
    cover(doc, title, f"{SYSTEM_NAME}配套管理制度", ORG_NAME,
          [f"编制单位：{ORG_NAME}", f"版本 {DOC_VERSION}｜生效日期 {DOC_DATE}",
           "本制度与2026-10-20数据库事实及后端预约规则保持一致"])
    h1(doc, "第一章 总则")
    para(doc, f"为保障{SYSTEM_NAME}所覆盖的十间实验室安全、有序运行，特制定本制度。"
              f"本制度自{DOC_DATE}起施行，由{ORG_NAME}负责解释。")
    cn = ["一", "二", "三", "四", "五", "六", "七", "八"]
    for i, (chap, clauses) in enumerate(chapters):
        if i == 0:
            for c in clauses:
                numbered(doc, [c])
            continue
        h1(doc, f"第{cn[i]}章 {chap}")
        numbered(doc, clauses)
    revision_table(doc, DOC_VERSION, DOC_DATE, [
        ("首次发布，条款与当前数据库状态（综合开放实验室关闭、3D打印机维修中等）逐一核对。", ORG_NAME),
    ])
    path = f"{OUT}/{title}.docx"
    doc.save(path)
    print("saved", path)


def main():
    for title, chapters in POLICIES:
        build(title, chapters)


if __name__ == "__main__":
    main()
